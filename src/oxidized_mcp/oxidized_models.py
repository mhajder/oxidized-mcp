# Constants that alias another model; nodes report the target class name.
MODEL_ALIASES: dict[str, str] = {
    "IOSXE": "IOS",
    "Supermicro": "EdgeCOS",
}

_CANONICAL: dict[str, str] = {name.casefold(): name for name in BUILTIN_MODELS} | {
    alias.casefold(): target for alias, target in MODEL_ALIASES.items()
}


def canonical_model(model: str) -> str:
    """Return the Oxidized class name for a model, or the input if unknown."""
    return _CANONICAL.get(model.strip().casefold(), model.strip())
